/* ================= MODAL GLOBAL CONTROLLERS ================= */
// Grab the modal elements once when the page loads
const modal = document.getElementById("image-modal");
const modalImg = document.getElementById("modal-img");
const closeBtn = document.querySelector(".close-btn");

// Only add these listeners if the modal exists in the HTML
if (modal && closeBtn) {
    // Close the modal when clicking the "X"
    closeBtn.addEventListener("click", () => {
        modal.style.display = "none";
    });

    // Close the modal when clicking the dark background
    modal.addEventListener("click", (event) => {
        if (event.target === modal) {
            modal.style.display = "none";
        }
    });
}

/* ================= INLINE ABOUT ME CONTROLLER ================= */
function toggleAboutSection() {
    const aboutExtended = document.getElementById("about-extended");
    const toggleBtn = document.getElementById("about-toggle-btn");

    if (!aboutExtended || !toggleBtn) return;

    if (aboutExtended.classList.contains("visible")) {
        aboutExtended.classList.remove("visible");
        toggleBtn.innerText = "read more >>";
    } else {
        aboutExtended.classList.add("visible");
        toggleBtn.innerText = "<< read less";

        setTimeout(() => {
            aboutExtended.scrollIntoView({ behavior: "smooth", block: "nearest" });
        }, 150);
    }
}

/* ================= INLINE WORKS CONTROLLER ================= */
function openInlineCampaign(cardElement, campaignIndex) {
    let extendedPanel = null;

    const campaignBlock = cardElement.closest('.campaign-block');
    if (campaignBlock) {
        extendedPanel = campaignBlock.querySelector('.works-extended-panel');
    }

    if (!extendedPanel) {
        const parentSection = cardElement.closest('.section') || cardElement.closest('.works-section');
        if (parentSection) {
            extendedPanel = parentSection.querySelector('.works-extended-panel');
        }
    }

    const dynamicDataset = portfolioCampaignMatrix[campaignIndex];
    if (!extendedPanel || !dynamicDataset) {
        console.error("Layout Target Error: Could not bind extended panel or dataset.");
        return;
    }

    // Inject Top Accordion & Intro Text
    extendedPanel.querySelector(".modal-title").innerText = dynamicDataset.title;
    extendedPanel.querySelector(".modal-desc").innerHTML = dynamicDataset.description;
    extendedPanel.querySelector(".modal-img-0").src = dynamicDataset.images[0];
    extendedPanel.querySelector(".modal-img-1").src = dynamicDataset.images[1];
    extendedPanel.querySelector(".modal-img-2").src = dynamicDataset.images[2];

    // Build and Inject Alternating Articles (Max 3)
    const articlesContainer = extendedPanel.querySelector(".campaign-articles");
    if (articlesContainer) {
        articlesContainer.innerHTML = "";
        if (dynamicDataset.articles && dynamicDataset.articles.length > 0) {
            let articleHTML = "";
            const limit = Math.min(dynamicDataset.articles.length, 3);
            for (let i = 0; i < limit; i++) {
                let article = dynamicDataset.articles[i];
                articleHTML += `
                    <div class="article-block">
                        <div class="article-img-wrapper">
                            <img src="${article.image}" alt="Social Media Content Preview">
                        </div>
                        <div class="article-text">
                            <p>${article.text}</p>
                        </div>
                    </div>
                `;
            }
            articlesContainer.innerHTML = articleHTML;
        }
    }

    // Build and Inject Gallery Carousel
    const galleryContainer = extendedPanel.querySelector(".gallery-track");
    if (galleryContainer) {
        galleryContainer.innerHTML = "";
        if (dynamicDataset.gallery && dynamicDataset.gallery.length > 0) {
            let galleryHTML = "";

            // 1. Loop through the new objects
            dynamicDataset.gallery.forEach(item => {
                // 2. Put 'item.thumb' as the visual image, and hide 'item.full' inside a data-full attribute
                galleryHTML += `<img class="gallery-img gallery-thumbnail" src="${item.thumb}" data-full="${item.full}" alt="Gallery portfolio item" style="cursor:pointer;">`;
            });
            galleryContainer.innerHTML = galleryHTML;

            // 3. Attach the click modal logic
            const newlyAddedImages = galleryContainer.querySelectorAll(".gallery-img");
            newlyAddedImages.forEach((img) => {
                img.addEventListener("click", () => {
                    if (modal && modalImg) {
                        modal.style.display = "block";

                        // 4. THE MAGIC TRICK: Instead of img.src, we grab the hidden data-full link!
                        modalImg.src = img.getAttribute("data-full");
                    }
                });
            });
        }
    }

    // Panel transition
    extendedPanel.classList.add('visible');

    const firstAccordionCard = extendedPanel.querySelector('.popup-mag-card');
    if (firstAccordionCard) {
        activateInlineAccordion(firstAccordionCard, 0);
    }

    setTimeout(() => {
        extendedPanel.scrollIntoView({ behavior: "smooth", block: "start" });
    }, 150);
}

function closeInlineCampaign(buttonElement) {
    const extendedPanel = buttonElement.closest('.works-extended-panel');
    if (extendedPanel) {
        extendedPanel.classList.remove('visible');
    }
}

function activateInlineAccordion(cardElement, targetActiveIndex) {
    const extendedPanel = cardElement.closest('.works-extended-panel');
    const interactiveCards = extendedPanel.querySelectorAll(".popup-mag-card");

    if (!interactiveCards.length) return;

    interactiveCards.forEach((cardNode, itemIndex) => {
        if (itemIndex === targetActiveIndex) {
            cardNode.classList.add("active");
            cardNode.classList.remove("blurred");
        } else {
            cardNode.classList.remove("active");
            cardNode.classList.add("blurred");
        }
    });
}

